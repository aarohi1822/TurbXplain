"""Regenerate the README results sections from results/metrics.json.

Two blocks in README.md are replaced: the headline table near the top (between
the RESULTS-HEADLINE markers) and the detailed results (between the RESULTS
markers). No numbers are typed by hand.  Run:  python -m src.evaluation.update_readme
"""

from __future__ import annotations

import json
from pathlib import Path

from src.config import PROJECT_ROOT

README = PROJECT_ROOT / "README.md"
METRICS = PROJECT_ROOT / "results" / "metrics.json"
START = "<!-- RESULTS:START (generated by `python -m src.evaluation.update_readme` from results/metrics.json; do not edit by hand) -->"
END = "<!-- RESULTS:END -->"
HEAD_START = "<!-- RESULTS-HEADLINE:START (generated by `python -m src.evaluation.update_readme` from results/metrics.json; do not edit by hand) -->"
HEAD_END = "<!-- RESULTS-HEADLINE:END -->"

NAMES = {
    "lstm": "LSTM only",
    "xgboost": "XGBoost only",
    "simple_average": "Simple average (0.5 / 0.5)",
    "ensemble": "Learned weighted ensemble",
}


def pm(stat: dict, fmt: str) -> str:
    return f"{stat['mean']:{fmt}} ± {stat['std']:{fmt}}"


def render_headline(m: dict) -> str:
    s = m["summary"]
    off = s["official_test"]
    n = len(m["protocol"]["seeds"])
    best = min(off, key=lambda k: off[k]["rmse"]["mean"])
    lines = [
        f"## Results: NASA C-MAPSS {m['dataset']}, official test protocol, {n} seeds",
        "",
        f"All numbers are for **{m['dataset']} only**: the official NASA test set, with RUL capped at "
        f"{m['protocol']['rul_cap']}. Each model makes **one prediction per test engine** from that engine's "
        f"last {m['protocol']['sequence_length']}-cycle window "
        f"({m['label_check']['test_engines_evaluated']} engines). The target is min(`RUL_{m['dataset']}`, "
        f"{m['protocol']['rul_cap']}). Values are mean ± std (sample std) over {n} seeds "
        f"({', '.join(map(str, m['protocol']['seeds']))}). The NASA score is the PHM08 asymmetric scoring "
        "function summed over the 100 test engines; lower is better.",
        "",
        "| Model | RMSE | NASA Score |",
        "|---|---:|---:|",
    ]
    for k, name in NAMES.items():
        bold = "**" if k == best else ""
        lines.append(f"| {bold}{name}{bold} | {bold}{pm(off[k]['rmse'], '.2f')}{bold} | {bold}{pm(off[k]['nasa_score'], '.1f')}{bold} |")
    w = s["ensemble_weight_lstm"]
    gain = off["lstm"]["rmse"]["mean"] - off["ensemble"]["rmse"]["mean"]
    lines += [
        "",
        f"![RMSE by model on the official FD001 test set, mean ± std over {n} seeds, with individual seeds as dots]"
        "(assets/ablation.png)",
        "",
        f"The ensemble weights are learned on a validation split of the training engines. Mean learned LSTM weight: "
        f"{w['mean']:.2f} ± {w['std']:.2f}. The ensemble improves on the LSTM alone by {gain:.2f} RMSE on average, "
        f"which is smaller than the seed-to-seed standard deviation (see [Limitations](#limitations)).",
        "",
        "Per-seed results, secondary metrics and the fingerprinting check are in [Detailed Results](#detailed-results).",
        "",
    ]
    return "\n".join(lines)


def render_details(m: dict) -> str:
    s = m["summary"]
    off, allw = s["official_test"], s["all_test_windows"]
    lines = [
        "## Detailed Results",
        "",
        "![Temporal SHAP values of the top 8 features over one FD001 test engine's life (XGBoost component only)]"
        "(assets/shap_waterfall.png)",
        "",
        "Temporal SHAP for one FD001 test engine, from the deployed model: the longest test trajectory whose SHAP "
        "values are all saved in `reports/shap_contributions.csv`. **XGBoost component only:** it does not explain "
        "the LSTM or the ensemble. Both figures are generated by `python -m src.evaluation.make_figures`, which "
        "fails if any plotted number differs from the saved results.",
        "",
        "<details><summary>Per-seed results and secondary metrics</summary>",
        "",
        "| Seed | LSTM RMSE | XGBoost RMSE | Ensemble RMSE | LSTM NASA | XGBoost NASA | Ensemble NASA | LSTM weight |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in m["runs"]:
        o = r["official_test"]
        lines.append(
            f"| {r['seed']} | {o['lstm']['rmse']:.2f} | {o['xgboost']['rmse']:.2f} | {o['ensemble']['rmse']:.2f} | "
            f"{o['lstm']['nasa_score']:.1f} | {o['xgboost']['nasa_score']:.1f} | {o['ensemble']['nasa_score']:.1f} | "
            f"{r['ensemble_weights']['lstm']:.2f} |"
        )
    lines += [
        "",
        "MAE and R² on the official test set:",
        "",
        "| Model | MAE | R² |",
        "|---|---:|---:|",
    ]
    for k, name in NAMES.items():
        lines.append(f"| {name} | {pm(off[k]['mae'], '.2f')} | {pm(off[k]['r2'], '.3f')} |")
    lines += [
        "",
        "For reference only (not comparable to the literature): the same models scored on every 30-cycle test window "
        "(10,196 windows). Earlier versions of this README reported this protocol. The NASA score is a sum, so it grows "
        "with the number of windows.",
        "",
        "| Model | RMSE (all windows) | NASA Score (all windows) |",
        "|---|---:|---:|",
    ]
    for k, name in NAMES.items():
        lines.append(f"| {name} | {pm(allw[k]['rmse'], '.2f')} | {pm(allw[k]['nasa_score'], '.0f')} |")
    lines += ["", "</details>", ""]

    # Fingerprints
    fp_sum = s["fingerprints"]
    slope = m["degradation_slope"]
    lines += [
        "### Degradation Fingerprinting (Exploratory)",
        "",
        "K-Means (k=3) on summary statistics of each engine's XGBoost SHAP trajectory. To test whether the cluster "
        "names mean anything, each cluster is compared with a **model-independent degradation slope**: the per-cycle OLS "
        "slope of a sensor health indicator (the mean of min-max-scaled informative sensors, oriented so that higher "
        "means more degraded). Slopes are shown ×1000. If the names held up, *fast-burn* would have the steepest "
        "slope and *slow-decay* a shallow one. (The code names cluster indices 0 / 1 / 2 fast-burn / slow-decay / "
        "sudden-failure; the dashboard shows them as Cluster A / B / C because the names are not validated.)",
        "",
        "| Engines clustered | Silhouette (mean ± std) | Seeds where fast-burn has steepest slope | Seeds where fast-burn > slow-decay |",
        "|---|---:|---:|---:|",
    ]
    cfg_names = {
        "as_implemented_first_2000_rows": "As implemented in the trainer (first 2,000 test SHAP rows)",
        "all_test_engines": "All 100 test engines",
    }
    for cfg, label in cfg_names.items():
        f = fp_sum[cfg]
        n_eng = m["runs"][0]["fingerprints"][cfg]["engines_clustered"]
        lines.append(
            f"| {label}: {n_eng} | {pm(f['silhouette'], '.3f')} | "
            f"{f['seeds_where_fast_burn_has_steepest_slope']}/{f['n_seeds']} | "
            f"{f['seeds_where_fast_burn_steeper_than_slow_decay']}/{f['n_seeds']} |"
        )
    lines += [
        "",
        "Per-cluster breakdown, all 100 test engines (count / mean slope ×1000 ± std):",
        "",
        "| Seed | Silhouette | fast-burn | slow-decay | sudden-failure |",
        "|---:|---:|---|---|---|",
    ]

    def cell(c: dict) -> str:
        if c["mean_degradation_slope"] is None:
            return f"{c['engine_count']} / –"
        sd = "" if c["std_degradation_slope"] is None else f" ± {1000 * c['std_degradation_slope']:.2f}"
        return f"{c['engine_count']} / {1000 * c['mean_degradation_slope']:.2f}{sd}"

    for r in m["runs"]:
        f = r["fingerprints"]["all_test_engines"]
        lines.append(f"| {r['seed']} | {f['silhouette']:.3f} | " + " | ".join(cell(c) for c in f["clusters"]) + " |")
    # Verdict, derived only from the numbers above.
    all_runs = [r["fingerprints"][c] for r in m["runs"] for c in cfg_names]
    max_sil = max(f["silhouette"] for f in all_runs)
    below = sum(f["silhouette"] < 0.25 for f in all_runs)
    singleton = sum(any(c["engine_count"] <= 1 for c in f["clusters"]) for f in all_runs)
    impl = fp_sum["as_implemented_first_2000_rows"]
    lines += [
        "",
        f"Health-indicator sensors: {', '.join(slope['sensors_used'])}.",
        "",
        "**Do the archetype labels hold up?** No, not in their current form:",
        "",
        f"- The silhouette score is below 0.25 in {below} of {len(all_runs)} clusterings and never above "
        f"{max_sil:.3f}. Below 0.25 is conventionally read as no substantial structure; 0.25 to 0.5 as weak structure.",
        f"- {singleton} of {len(all_runs)} clusterings contain a single-engine cluster, usually *sudden-failure*.",
        f"- In the configuration the trainer uses, *fast-burn* has the steepest degradation slope in "
        f"{impl['seeds_where_fast_burn_has_steepest_slope']}/{impl['n_seeds']} seeds. On all 100 engines the "
        "ordering is mostly as named, but the within-cluster spread of slopes is about as large as the gap between "
        "cluster means.",
        "",
        "The cluster names are cluster indices with descriptive names attached. They are not validated failure types.",
        "",
    ]
    return "\n".join(lines)


def replace_block(text: str, start: str, end: str, content: str) -> str:
    if start not in text or end not in text:
        raise SystemExit(f"README is missing the markers {start[:30]}... / {end}.")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return head + start + "\n" + content + end + tail


def main() -> None:
    metrics = json.loads(METRICS.read_text())
    readme = README.read_text()
    readme = replace_block(readme, HEAD_START, HEAD_END, render_headline(metrics))
    readme = replace_block(readme, START, END, render_details(metrics))
    README.write_text(readme)
    print("README results sections updated from", METRICS)


if __name__ == "__main__":
    main()
